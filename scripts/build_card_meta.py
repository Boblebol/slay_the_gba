"""Write include/engine/card_meta.h: the rarity and the pool of every engine card, from bible/data.

The engine draws cards at random by rarity and by pool (CombatEngine::random_card). Both come from the
reference, so they are generated instead of typed by hand next to each card.

Run from the repository root after adding a card to `enum class CardId`:

    uv run scripts/build_card_meta.py

`uv run scripts/build_card_meta.py --check` fails when the header is out of date (what the test does).
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CARD_H = ROOT / "include" / "engine" / "card.h"
DATA = ROOT / "bible" / "data" / "card_v0.111.0.json"
OUT = ROOT / "include" / "engine" / "card_meta.h"

# Engine card names that differ from the identifier of the same card in bible/data (as in progress.py).
ALIASES = {"POISON_STAB": "POISONED_STAB", "NULL_CARD": "NULL", "VOID_CARD": "VOID"}
# The engine has one Strike and one Defend for the five heroes: Basic cards of no pool in particular.
SHARED_BASICS = {"STRIKE", "DEFEND"}
RARITIES = {"Basic", "Common", "Uncommon", "Rare", "Ancient", "Event", "Curse", "Quest"}
POOLS = {"Ironclad", "Silent", "Defect", "Regent", "Necrobinder", "Colorless", "Event", "Curse", "Quest"}


def engine_cards() -> list[str]:
    """Names of `enum class CardId`, in order, without COUNT."""
    header = re.sub(r"//.*", "", CARD_H.read_text())
    body = re.search(r"enum class CardId[^{]*\{(.*?)\}", header, re.S)
    if not body:
        raise SystemExit("build_card_meta: enum CardId not found in include/engine/card.h")
    names = re.findall(r"[A-Z_][A-Z0-9_]*", re.sub(r"=\s*\d+", "", body.group(1)))
    return [name for name in names if name != "COUNT"]


def reference_cards() -> dict[str, dict]:
    data = json.loads(DATA.read_text())
    cards = data["cards"] if isinstance(data, dict) else data
    return {card["id"]: card for card in cards}


def meta_of(name: str, reference: dict[str, dict]) -> tuple[str, str]:
    """(CardRarity, CardPool) enumerators of one engine card."""
    if name in SHARED_BASICS:
        return "BASIC", "NONE"
    card = reference.get(ALIASES.get(name, name))
    if card is None:
        return "NONE", "NONE"  # Status card or token: not in the reference
    rarity, pool = card["rarity"], card["pool"]
    if rarity not in RARITIES or pool not in POOLS:
        raise SystemExit(f"build_card_meta: {name} has an unknown rarity or pool ({rarity}, {pool})")
    return rarity.upper(), pool.upper()


def render() -> str:
    reference = reference_cards()
    rows = []
    for name in engine_cards():
        rarity, pool = meta_of(name, reference)
        rows.append(f"    {{ CardRarity::{rarity}, CardPool::{pool} }}, // {name}")
    return "\n".join([
        "// Generated by scripts/build_card_meta.py from bible/data: do not edit by hand.",
        "// One entry per CardId, in the order of the enum.",
        "#pragma once",
        '#include "engine/card.h"',
        "",
        "namespace engine {",
        "",
        "inline constexpr CardMeta CARD_META[] = {",
        *rows,
        "};",
        "",
        "} // namespace engine",
        "",
    ])


def main() -> None:
    text = render()
    if "--check" in sys.argv[1:]:
        if not OUT.exists() or OUT.read_text() != text:
            raise SystemExit("build_card_meta: include/engine/card_meta.h is out of date, "
                             "run `uv run scripts/build_card_meta.py`")
        return
    OUT.write_text(text)
    print(f"Written {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
